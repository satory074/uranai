export function honmeiNumber(year: number, month: number, day: number): number {
  // 立春cutoff: 1/1 〜 2/3 は前年扱い
  let y = year;
  if (month === 1 || (month === 2 && day < 4)) y -= 1;

  const digits = String(y).split('').reduce((s, c) => s + Number(c), 0);
  const reduce = (n: number): number => (n < 10 ? n : reduce(String(n).split('').reduce((s, c) => s + Number(c), 0)));
  const root = reduce(digits);
  const star = 11 - root;
  // star が 1〜9 の範囲に収まるよう調整
  if (star <= 0) return star + 9;
  if (star > 9) return star - 9;
  return star;
}
