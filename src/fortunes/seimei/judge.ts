export function tonalLabelFor(position: Position, strokes: number): { tone: Tone; label: string; hint: string } {
  const reduced = ((strokes - 1) % 81) + 1;
  const t = STROKE_TONE_BY_NUMBER[reduced] ?? { tone: 'cool' as Tone, label: '静か' };
  const hint = HINTS[position][t.tone];
  return { tone: t.tone, label: t.label, hint };
}
